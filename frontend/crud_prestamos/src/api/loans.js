import api from './client'

export const getResources = () => api.get('/prestamos/admin/recursos/')
export const createResource = data => api.post('/prestamos/admin/recursos/', data)
export const updateResource = (id, data) => api.put(`/prestamos/admin/recursos/${id}/`, data)
export const deleteResource = id => api.delete(`/prestamos/admin/recursos/${id}/`)
export const getCategories = () => api.get('/prestamos/admin/categorias/')
export const createCategory = data => api.post('/prestamos/admin/categorias/', data)
export const updateCategory = (id, data) => api.put(`/prestamos/admin/categorias/${id}/`, data)
export const deleteCategory = id => api.delete(`/prestamos/admin/categorias/${id}/`)
export const getCopies = resourceId => api.get(`/prestamos/admin/recursos/${resourceId}/ejemplares/`)
export const createCopy = (resourceId, data) => api.post(`/prestamos/admin/recursos/${resourceId}/ejemplares/`, data)
export const updateCopy = (id, data) => api.put(`/prestamos/admin/ejemplares/${id}/`, data)
export const deleteCopy = id => api.delete(`/prestamos/admin/ejemplares/${id}/`)
export const getPolicies = () => api.get('/prestamos/admin/politicas/')
export const createPolicy = data => api.post('/prestamos/admin/politicas/', data)
export const updatePolicy = (id, data) => api.put(`/prestamos/admin/politicas/${id}/`, data)
export const deletePolicy = id => api.delete(`/prestamos/admin/politicas/${id}/`)
export const getLoans = state => api.get('/prestamos/admin/reservas/', { params: state ? { estado: state } : {} })
export const returnLoan = id => api.post(`/prestamos/admin/reservas/${id}/devolver/`)
